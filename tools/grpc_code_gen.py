import glob
import os
import re
import shutil
import sys
from importlib import metadata
from pathlib import Path

from grpc_tools import protoc
from packaging import version

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

grpc_tools_version = metadata.version('grpcio-tools')
dest_dir = 'skywalking/protocol'
src_dir = 'protocol'
pyproject = Path(__file__).resolve().parents[1] / 'pyproject.toml'

gencode_header = re.compile(r'^# Protobuf Python Version: (\S+)$', re.MULTILINE)
protobuf_floor_spec = re.compile(r'^protobuf\s*=\s*"[^"]*>=\s*([0-9][0-9.]*)', re.MULTILINE)


def touch(filename):
    open(filename, 'a').close()


def check_gencode_versions():
    """protobuf refuses to load gencode newer than its runtime, so code generated by a newer
    grpcio-tools than the `protobuf` floor in pyproject.toml breaks `import skywalking` for
    anyone sitting on that floor."""
    floor = protobuf_floor_spec.search(pyproject.read_text(encoding='utf-8'))
    if floor is None:
        sys.exit('Cannot find the protobuf lower bound in pyproject.toml')
    floor = version.parse(floor.group(1))

    found = set()
    for pb2_file in glob.iglob(os.path.join(dest_dir, '**/*_pb2.py'), recursive=True):
        header = gencode_header.search(Path(pb2_file).read_text(encoding='utf-8'))
        if header is None:
            sys.exit(f'{pb2_file} has no "Protobuf Python Version" header; cannot verify it')
        found.add(header.group(1))

    too_new = sorted(v for v in found if version.parse(v) > floor)
    if too_new:
        sys.exit(f'grpcio-tools {grpc_tools_version} generated code for protobuf {", ".join(too_new)}, '
                 f'newer than the protobuf>={floor} floor in pyproject.toml. '
                 f'Pin an older grpcio-tools (GRPC_TOOLS_VERSION in the Makefile).')


def codegen():
    protos = list(glob.iglob(f'{src_dir}/**/*.proto', recursive=True))
    if not protos:
        sys.exit(f'No .proto sources under ./{src_dir}; run `git submodule update --init` first.')

    # The whole directory is generated (and git-ignored); start clean so stale files from an
    # earlier run with another grpcio-tools version never end up in the package.
    shutil.rmtree(dest_dir, ignore_errors=True)
    os.mkdir(dest_dir)

    touch(os.path.join(dest_dir, '__init__.py'))
    protoc_args = [
        'grpc_tools.protoc',
        f'--proto_path={src_dir}',
        f'--python_out={dest_dir}',
        f'--grpc_python_out={dest_dir}'
    ]
    if version.parse(grpc_tools_version) >= version.parse('1.49.0'):
        # https://github.com/grpc/grpc/issues/31247
        protoc_args += [f'--pyi_out={dest_dir}']
    protoc_args += protos
    if protoc.main(protoc_args) != 0:
        sys.exit('grpc_tools.protoc failed')

    for py_file in glob.iglob(os.path.join(dest_dir, '**/*.py'), recursive=True):
        touch(os.path.join(os.path.dirname(py_file), '__init__.py'))
        with open(py_file, 'r+') as file:
            code = file.read()
            file.seek(0)
            file.write(re.sub(r'from ((?!\.).+) (import .+_pb2.*)', 'from ..\\1 \\2', code))
            file.truncate()

    check_gencode_versions()


if __name__ == '__main__':
    codegen()
